/** 内置 Agent 角色 → 稳定形状映射（未知角色走带种子的哈希兜底）。 */
const ROLE_SHAPE: Record<string, BotShapeId> = {
  project_architect: "whale",
  agent_engineer: "star",
  frontend_designer: "moon",
  knowledge_manager: "squircle",
  qa_engineer: "gumdrop",
  operations_engineer: "squircle",
}

function hashString(value: string): number {
  let hash = 2166136261
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index)
    hash = Math.imul(hash, 16777619)
  }
  return hash >>> 0
}

export function isBotShapeId(value: unknown): value is BotShapeId {
  return (
    typeof value === "string" &&
    (BOT_SHAPE_IDS as readonly string[]).includes(value)
  )
}

/** 角色 → 形状：已知角色固定映射，未知角色用 FNV-1a 哈希稳定兜底。 */
export function botShapeForRole(role: string | null | undefined): BotShapeId {
  const normalized = (role ?? "").trim().toLowerCase()
  const mapped = ROLE_SHAPE[normalized]
  if (mapped) return mapped
  return BOT_SHAPE_IDS[hashString(normalized || "agent") % BOT_SHAPE_IDS.length]
}

/** 任意种子（agent id / 名称）→ 形状，保证同一实体每次渲染一致。 */
export function botShapeForSeed(seed: string | number): BotShapeId {
  return BOT_SHAPE_IDS[hashString(String(seed)) % BOT_SHAPE_IDS.length]
}

export function botShapeLabel(shape: BotShapeId): string {
  return BOT_SHAPES[shape].label
}
